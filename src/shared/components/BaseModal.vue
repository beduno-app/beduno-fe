<script setup lang="ts">
defineProps<{
  title: string
}>()

const emit = defineEmits<{
  close: []
}>()

function onBackdrop(e: MouseEvent) {
  if (e.target === e.currentTarget) {
    emit('close')
  }
}
</script>

<template>
  <Teleport to="body">
    <div
      class="modal-backdrop"
      @click="onBackdrop"
    >
      <div
        class="modal"
        role="dialog"
        aria-modal="true"
      >
        <div class="modal-header">
          <h3 class="modal-title">
            {{ title }}
          </h3>
          <button
            class="modal-close"
            @click="$emit('close')"
          >
            &times;
          </button>
        </div>
        <div class="modal-body">
          <slot />
        </div>
        <div
          v-if="$slots.footer"
          class="modal-footer"
        >
          <slot name="footer" />
        </div>
      </div>
    </div>
  </Teleport>
</template>

